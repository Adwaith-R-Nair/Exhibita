// Source records: the facts Exhibita reads from systems of record before they become evidence.
//
// Two shapes live here:
// - Rows and Demo* records: what the demo generator produces and the setup wizard writes to Forge SQL,
//   Jira and Confluence. Jira and Confluence objects carry a stable `ref`, because their keys are only
//   known once the wizard has created them.
// - Observed* records and CollectInput: what the evidence collectors read back, with real keys and
//   URLs. Collectors turn a CollectInput into EvidenceItems with provenance (AGENTS.md invariant 5).
//
// Nothing here imports @forge/*.

import type { CardNetwork, Currency, Dispute, MinorUnits, ReasonKey, Recommendation } from '../types';

// ---------------------------------------------------------------------------------------------------
// Rows (Forge SQL). Ids are generated by the demo generator and are stable for a given seed.
// ---------------------------------------------------------------------------------------------------

export interface CustomerRow {
  /** cus_demo_0001 */
  id: string;
  name: string;
  /** Always @example.com. */
  email: string;
  createdAt: string;
}

export interface ProductRow {
  sku: string;
  name: string;
  /** The description shown at checkout. */
  description: string;
  kind: 'physical' | 'subscription' | 'digital';
}

export type ShipStatus = 'delivered' | 'in-transit' | 'returned-to-sender' | 'lost';
export type CheckOutcome = 'match' | 'mismatch' | 'unavailable';
export type ThreeDSOutcome = 'authenticated' | 'attempted' | 'not-attempted' | 'failed';

export interface OrderRow {
  /** ORD-10001 */
  id: string;
  customerId: string;
  sku: string;
  amount: MinorUnits;
  currency: Currency;
  purchasedAt: string;
  ip: string;
  deviceId: string;
  /** Version of the refund and returns policy the customer accepted at checkout (for example "v1"), or null. */
  termsAcceptedVersion: string | null;
  // Fulfilment. All null for digital goods and subscriptions.
  carrier: string | null;
  tracking: string | null;
  shipStatus: ShipStatus | null;
  deliveredAt: string | null;
  /** Delivered to the shipping address the customer gave at checkout. */
  addressMatch: boolean | null;
  signedBy: string | null;
  /** The signature name matches the customer's name. */
  signatureNameMatch: boolean | null;
  /** What was delivered matches the description at purchase (from fulfilment QA). Null when unknown. */
  descriptionMatches: boolean | null;
  // Payment checks.
  threeDS: ThreeDSOutcome;
  avs: CheckOutcome;
  cvv: CheckOutcome;
  // Subscriptions only.
  subscriptionCancelledAt: string | null;
  // Identity of the payer, for Compelling Evidence 3.0 (review B8). Null when not captured.
  /** Stable fingerprint of the card used; same card means same fingerprint. */
  cardFingerprint: string | null;
  cardNetwork: CardNetwork;
  /** The customer's account or login id at the merchant. */
  accountId: string | null;
  /** Hash of the full shipping address. */
  shippingAddressHash: string | null;
  /** The issuer reported this transaction as fraud (a TC40 report). */
  fraudReported: boolean;
}

export interface ChargeRow {
  /** ch_demo_0001 */
  id: string;
  orderId: string;
  customerId: string;
  amount: MinorUnits;
  currency: Currency;
  chargedAt: string;
  /** Set when this charge was refunded in full. */
  refundedAt: string | null;
  /**
   * How much the processor has actually refunded on this charge. This is the processor's view, synced
   * from its events; the refunds table is the merchant's own refund service. They can disagree, which
   * is exactly what reconciliation looks for.
   */
  amountRefunded: MinorUnits;
}

/**
 * A refund's lifecycle. "approved" means a person said yes; only "completed" means money moved.
 * An approved refund that never completed is owed to the customer.
 */
export type RefundStatus = 'requested' | 'approved' | 'initiated' | 'completed' | 'declined' | 'voided';
// voided: cancelled because the disputed amount was settled by accepting the chargeback, so a later
// replay of stuck refunds cannot pay the customer twice (D-17, review D).

export interface RefundRow {
  /** REF-1001 */
  id: string;
  orderId: string;
  chargeId: string;
  amount: MinorUnits;
  currency: Currency;
  status: RefundStatus;
  requestedAt: string;
  approvedAt: string | null;
  completedAt: string | null;
  declineReason: string | null;
}

/**
 * An explicit, recorded link between an incident and a refund or charge it affected, for example from
 * the incident's postmortem. This is the only way an incident becomes a cause (invariant 7).
 */
export interface IncidentImpactRow {
  incidentRef: string;
  refundId: string | null;
  chargeId: string | null;
}

export interface OutcomeRow {
  disputeId: string;
  reasonCode: ReasonKey;
  amount: MinorUnits;
  currency: Currency;
  /** What the team did. */
  decision: 'fought' | 'accepted';
  result: 'won' | 'lost' | 'accepted';
  closedAt: string;
  /** For losses: the plain-English reason the network gave, used for "why are we losing?". */
  lossReason: string | null;
}

// ---------------------------------------------------------------------------------------------------
// Demo records for Jira and Confluence (created by the wizard; keys assigned on creation).
// ---------------------------------------------------------------------------------------------------

export interface DemoDeploy {
  ref: string;
  /** "Deploy refund-worker 3.2" */
  title: string;
  description: string;
  at: string;
}

export type IncidentEffect = 'dropped-refunds' | 'duplicate-charges' | 'other';

export interface DemoIncident {
  ref: string;
  title: string;
  description: string;
  effect: IncidentEffect;
  windowStart: string;
  windowEnd: string | null;
  /** Deploy that caused it, recorded as an explicit Jira link. Null for incidents with no known cause. */
  causedByDeployRef: string | null;
}

export interface TicketMessage {
  author: 'customer' | 'agent';
  at: string;
  text: string;
}

export interface DemoTicket {
  ref: string;
  customerId: string;
  orderId: string | null;
  summary: string;
  createdAt: string;
  /** First message is the ticket description; the rest become comments. */
  messages: TicketMessage[];
  /** Refund this ticket asked about, if any. */
  refundId: string | null;
  /** Incident this ticket is explicitly linked to in Jira, if any. */
  linkedIncidentRef: string | null;
}

export type PolicyKind = 'refund-returns' | 'shipping' | 'cancellation';

export interface DemoPolicyVersion {
  version: string;
  effectiveFrom: string;
  /** Null while still in force. */
  effectiveTo: string | null;
  /** Confluence storage-format body. */
  body: string;
}

export interface DemoPolicy {
  ref: string;
  kind: PolicyKind;
  title: string;
  /** Oldest first. */
  versions: DemoPolicyVersion[];
}

export interface DemoDispute {
  /** The Stripe-compatible `charge.dispute.created` event, as the webhook receives it. */
  payload: unknown;
  /** Reason after normalisation, for tests. */
  reasonCode: ReasonKey;
  /** What Exhibita should recommend after collecting evidence (rubric plus challenge). */
  expected: Recommendation;
  /** One line on what this case demonstrates, for tests and the demo guide. */
  scenario: string;
  /** The hero case of the demo story. Exactly one dispute has this set. */
  hero?: boolean;
}

export interface DemoWorld {
  seed: number;
  /** Anchor time; every other date is relative to it so deadlines stay in the future. */
  now: string;
  customers: CustomerRow[];
  products: ProductRow[];
  orders: OrderRow[];
  charges: ChargeRow[];
  refunds: RefundRow[];
  deploys: DemoDeploy[];
  incidents: DemoIncident[];
  impacts: IncidentImpactRow[];
  tickets: DemoTicket[];
  policies: DemoPolicy[];
  disputes: DemoDispute[];
  outcomes: OutcomeRow[];
}

// ---------------------------------------------------------------------------------------------------
// Observed records: what the collectors read back, with real keys and URLs.
// ---------------------------------------------------------------------------------------------------

export interface ObservedRefund extends RefundRow {
  /** Incident key, only when an IncidentImpactRow or a Jira link names this refund. */
  linkedIncident: string | null;
  /** The deploy that incident is linked to, if any. */
  linkedDeploy: string | null;
  /** The support ticket about this refund, if any. */
  ticketKey: string | null;
  ticketUrl?: string;
}

export interface ObservedTicket {
  key: string;
  url?: string;
  /** The order the ticket is about, when known; tickets about other orders must not count (review B4). */
  orderId: string | null;
  createdAt: string;
  messages: TicketMessage[];
}

export interface ObservedIncident {
  key: string;
  url?: string;
  title: string;
  effect: IncidentEffect;
  windowStart: string;
  windowEnd: string | null;
  linkedDeploy: string | null;
  /**
   * explicit: an impact row or Jira link names this dispute's refund or charge.
   * none: it is here only because its window overlaps the purchase; never a cause.
   */
  link: 'explicit' | 'none';
}

export interface ObservedPolicyVersion {
  pageId: string;
  title: string;
  url?: string;
  kind: PolicyKind;
  version: string;
  effectiveFrom: string;
  effectiveTo: string | null;
}

export interface PriorOrder {
  id: string;
  purchasedAt: string;
  ip: string;
  deviceId: string;
  disputed: boolean;
  cardFingerprint: string | null;
  accountId: string | null;
  shippingAddressHash: string | null;
  fraudReported: boolean;
}

/** The systems a dispute's evidence is read from, in the order the live collector reads them. */
export const COLLECT_SOURCES = ['order', 'tickets', 'refunds', 'settlements', 'incidents', 'policies'] as const;
// settlements: the processor's view of refunds (charges.amountRefunded), read after the merchant's own
// refund records so the panel shows the checklist first and then the reconciliation (review D1).
export type CollectSource = (typeof COLLECT_SOURCES)[number];

export interface CollectInput {
  /**
   * Sources not read yet. Their lists are empty but mean "unknown", not "none", so no evidence (and
   * in particular no recorded absence) may come from them. Omitted when everything has been read.
   */
  pending?: readonly CollectSource[];
  dispute: Dispute;
  order: OrderRow | null;
  product: ProductRow | null;
  /** Every charge on this order, plus the customer's other charges of the same amount within 7 days. */
  charges: ChargeRow[];
  /** Refunds on this order. */
  refunds: ObservedRefund[];
  /** The customer's earlier orders, for Compelling Evidence 3.0. */
  priorOrders: PriorOrder[];
  /** Support tickets from this customer. */
  tickets: ObservedTicket[];
  /** Incidents linked to this dispute, plus any whose window overlaps the purchase (link: 'none'). */
  incidents: ObservedIncident[];
  /** Every version of every policy page. */
  policies: ObservedPolicyVersion[];
}
